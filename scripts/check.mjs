import { readFile, access, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
const root = fileURLToPath(new URL('../', import.meta.url));
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
if (new Set(ids).size !== ids.length) throw new Error('Duplicate HTML IDs');
const localLinks = [...html.matchAll(/(?:src|href)="([^"#][^"]*)"/g)].map(m=>m[1]).filter(s=>!/^https?:/.test(s));
for (const file of localLinks) await access(path.join(root, file));
for (const [, id] of html.matchAll(/href="#([^"]+)"/g)) if (!ids.includes(id)) throw new Error(`Missing anchor: ${id}`);
for (const [, id] of html.matchAll(/aria-(?:controls|labelledby)="([^"]+)"/g)) if (!ids.includes(id)) throw new Error(`Missing ARIA target: ${id}`);
for (const tag of html.matchAll(/<a\b[^>]*target="_blank"[^>]*>/g)) if (!tag[0].includes('noopener noreferrer')) throw new Error('Unsafe external target');
new vm.Script(await readFile(path.join(root,'script.js'),'utf8'));
const btc = 'bc1psx8s9v3g8722chumclkgmuu6jx3mkrzdk43ryghkv5tds7urn3ds37h8rt';
const sol = 'FEGRudjUfxS1Pfe4aJzx9YXkGwDP5XhTEx8isZpc1DSa';
if (!html.includes(btc) || !html.includes(sol)) throw new Error('Donation address mismatch');
if (!html.includes('releases/download/windows-preview/ACID-RECALL-Windows-x64.zip')) throw new Error('Wrong release link');
const assets = ['studio-full.webp','studio-preview.webp','dual-acid.webp','rhythm-machines.webp','sampler-fx.webp','logo.svg','qr-bitcoin.png','qr-solana.png','anton-latin.woff2'];
let bytes = 0;
for (const file of assets) bytes += (await stat(path.join(root,'assets',file))).size;
if (bytes > 1000000) throw new Error('Asset budget exceeded');
console.log(`Passed: local assets, anchors, ARIA references, external links, JavaScript syntax, donation addresses, Windows download. Main assets: ${Math.round(bytes/1024)} KB.`);
